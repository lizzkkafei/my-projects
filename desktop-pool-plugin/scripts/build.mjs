#!/usr/bin/env node
/**
 * Build the single-file DSH client bundle `client.js`.
 *
 * The Harness Web client loads exactly one self-contained script per plugin via
 * `window.__ModuleLoader__.load({ id, factory })`. This script:
 *
 *   1. makes sure `game/bundle.js` exists (rebuilds it with esbuild when the
 *      game's own node_modules are installed, otherwise reuses the committed
 *      bundle),
 *   2. inlines the game stylesheet from `game/index.html`, scoping the
 *      document-level selectors so nothing leaks out of the shadow root,
 *   3. inlines the game body markup (scripts stripped),
 *   4. concatenates the plugin sources from `src/`, which mount the game into a
 *      shadow root inside a full-frame overlay.
 *
 * Usage: node scripts/build.mjs
 */
import fs from 'node:fs';
import path from 'node:path';
import { execFileSync } from 'node:child_process';
import { fileURLToPath } from 'node:url';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const read = (relative) => fs.readFileSync(path.join(root, relative), 'utf8');
const exists = (relative) => fs.existsSync(path.join(root, relative));

const pkg = JSON.parse(read('package.json'));
const bundleId = pkg.name;

/* ------------------------------------------------------------------ *
 * 1. The game bundle
 * ------------------------------------------------------------------ */

const GAME_DIR = 'game';
const GAME_BUNDLE = `${GAME_DIR}/bundle.js`;

if (!exists(GAME_BUNDLE)) {
  if (!exists(`${GAME_DIR}/node_modules`)) {
    throw new Error(
      `missing ${GAME_BUNDLE}. Run "cd ${GAME_DIR} && npm install && node build.mjs" first, ` +
      'or commit the prebuilt bundle.',
    );
  }
  console.log('building game bundle…');
  execFileSync(process.execPath, ['build.mjs'], { cwd: path.join(root, GAME_DIR), stdio: 'inherit' });
}
if (!exists(GAME_BUNDLE)) throw new Error(`${GAME_BUNDLE} still missing after build`);

const GAME_JS = read(GAME_BUNDLE);

/* ------------------------------------------------------------------ *
 * 2. Stylesheet from index.html, scoped for a shadow root
 * ------------------------------------------------------------------ */

const html = read(`${GAME_DIR}/index.html`);
const styleMatch = html.match(/<style[^>]*>([\s\S]*?)<\/style>/i);
if (!styleMatch) throw new Error('game/index.html: no <style> block found');
const rawCss = styleMatch[1];

function scopeCss(css) {
  return css
    // `:root` custom properties live on the shadow host instead.
    .replace(/:root\b/g, ':host')
    // Document-level element selectors cannot match inside a shadow root;
    // map them onto the host so background / sizing still apply.
    .replace(/(^|\})\s*html\s*,\s*body\s*\{/g, '$1\n:host { display: block; width: 100%; height: 100%; }')
    .replace(/(^|\})\s*html\s*\{/g, '$1\n:host { display: block; width: 100%; height: 100%; }')
    .replace(/(^|\})\s*body\s*\{/g, '$1\n:host { display: block; width: 100%; height: 100%; }');
}

// The game's markup now lives inside `.zp-surface` (a child of the shadow host).
// Give both layers an explicit box so the canvas can size itself from its
// parent instead of the window.
const HOST_CSS = [
  ':host { display: block; position: absolute; inset: 0; overflow: hidden; }',
  '.zp-surface { position: absolute; inset: 0; overflow: hidden; }',
  '#c { width: 100% !important; height: 100% !important; }',
].join('\n');

const GAME_CSS = HOST_CSS + '\n' + scopeCss(rawCss);

/* ------------------------------------------------------------------ *
 * 3. Markup: the body of index.html, without its scripts
 * ------------------------------------------------------------------ */

const bodyMatch = html.match(/<body[^>]*>([\s\S]*)<\/body>/i);
if (!bodyMatch) throw new Error('game/index.html: no <body> found');
const GAME_HTML = bodyMatch[1]
  .replace(/<script\b[\s\S]*?<\/script>/gi, '')
  .trim();

if (!GAME_HTML.includes('id="c"')) throw new Error('game/index.html: body is missing the #c canvas');

/* ------------------------------------------------------------------ *
 * 4. Assemble client.js
 * ------------------------------------------------------------------ */

for (const file of ['src/entry.js']) {
  if (!exists(file)) throw new Error(`missing plugin source: ${file}`);
}
const entrySource = read('src/entry.js');

if (/\bfunction\s+__bootPool\b/.test(GAME_JS)) {
  throw new Error('game bundle already defines __bootPool — refusing to nest twice');
}

const parts = [
  `/* ${pkg.name} v${pkg.version} — generated by scripts/build.mjs. Do not edit by hand. */`,
  '/* Bundles three.js (MIT, Copyright 2010-2025 Three.js Authors) and the desktop-pool game. */',
  'window.__ModuleLoader__.load({',
  `  id: ${JSON.stringify(bundleId)},`,
  '  factory(require) {',
  '    "use strict";',
  '    const React = require("react");',
  '    const h = React.createElement;',
  '',
  `    const GAME_CSS = ${JSON.stringify(GAME_CSS)};`,
  `    const GAME_HTML = ${JSON.stringify(GAME_HTML)};`,
  '',
  '    /* ---- the game bundle, wrapped so it only runs when the overlay mounts ---- */',
  '    function __bootPool() {',
  GAME_JS,
  '    }',
  '',
  entrySource,
  '',
  '    return {',
  '      inject,',
  '      apply,',
  '      __debug: { mountPool, openTable, closeTable, isOpen: () => !!overlay, html: GAME_HTML, css: GAME_CSS },',
  '    };',
  '  },',
  '});',
  '',
];

const output = parts.join('\n');
fs.writeFileSync(path.join(root, 'client.js'), output);
execFileSync(process.execPath, ['--check', path.join(root, 'client.js')], { stdio: 'pipe' });

const megabyte = (fs.statSync(path.join(root, 'client.js')).size / 1024 / 1024).toFixed(2);
console.log(`client.js written (${megabyte} MB, id ${bundleId})`);
