#!/usr/bin/env node
/**
 * Build the single-file browser bundle `client.js` for the Liyin workbench.
 * The Harness Web client loads one self-contained script per plugin via
 * `window.__ModuleLoader__.load({ id, factory })`; this script concatenates
 * the CommonJS-style sources plus the stylesheet string, then syntax-checks
 * the output.
 *
 * Usage: node scripts/build.mjs
 */
import fs from 'node:fs';
import path from 'node:path';
import { execFileSync } from 'node:child_process';
import { fileURLToPath } from 'node:url';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const read = (relative) => fs.readFileSync(path.join(root, relative), 'utf8');
const pkg = JSON.parse(read('package.json'));

const jsModules = ['entry'];
const cssModules = ['styles.css'];

for (const id of jsModules) {
  if (!fs.existsSync(path.join(root, `src/${id}.js`))) throw new Error(`missing source: src/${id}.js`);
}
for (const id of cssModules) {
  if (!fs.existsSync(path.join(root, `src/${id}`))) throw new Error(`missing stylesheet: src/${id}`);
}

function checkCommonJs(source, filename) {
  if (/^\s*import\s/m.test(source) || /^\s*export\s/m.test(source)) {
    throw new Error(`${filename}: use CommonJS (module.exports / require), not ESM`);
  }
  if (source.includes('__ModuleLoader__')) {
    throw new Error(`${filename}: only the build output may know about __ModuleLoader__`);
  }
  return source;
}

function wrapJs(id, source) {
  const body = checkCommonJs(source, `src/${id}.js`).trimEnd();
  return [
    `    __modules[${JSON.stringify(id)}] = function (module, exports, require) {`,
    '      "use strict";',
    body,
    '    };',
    '',
  ].join('\n');
}

function wrapCss(id, source) {
  return [
    `    __modules[${JSON.stringify(id)}] = function (module) {`,
    `      module.exports = ${JSON.stringify(source)};`,
    '    };',
    '',
  ].join('\n');
}

const parts = [
  `/* ${pkg.name} v${pkg.version} — generated by scripts/build.mjs. Do not edit by hand. */`,
  'window.__ModuleLoader__.load({',
  `  id: ${JSON.stringify(pkg.name)},`,
  '  factory(require) {',
  '    "use strict";',
  '    const React = require("react");',
  '    const h = React.createElement;',
  '    const __modules = Object.create(null);',
  '    const __cache = Object.create(null);',
  '    function __load(id) {',
  '      if (id === "react") return React;',
  '      const key = id.startsWith("./") ? id.slice(2) : id;',
  '      if (__cache[key] !== undefined) return __cache[key].exports;',
  '      const mod = { exports: {} };',
  '      __cache[key] = mod;',
  '      const factory = __modules[key];',
  '      if (typeof factory !== "function") throw new Error("zhizhen-liyin: unknown module " + id);',
  '      factory(mod, mod.exports, __load);',
  '      return mod.exports;',
  '    }',
  '',
  ...cssModules.map((id) => wrapCss(id, read(`src/${id}`))),
  ...jsModules.map((id) => wrapJs(id, read(`src/${id}.js`))),
  '    return __load("./entry");',
  '  },',
  '});',
  '',
];

const output = parts.join('\n');
const target = path.join(root, 'client.js');
fs.writeFileSync(target, output);
try {
  execFileSync(process.execPath, ['--check', target], { stdio: 'pipe' });
} catch (error) {
  throw new Error(`client.js failed node --check:\n${error.stderr?.toString() ?? error.message}`);
}
const size = (fs.statSync(target).size / 1024).toFixed(1);
console.log(`client.js written (${size} KiB, id ${pkg.name})`);
