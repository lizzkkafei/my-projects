#!/usr/bin/env node
/**
 * Build the single-file browser bundle `client.js`.
 *
 * The Harness Web client loads exactly one self-contained script per plugin via
 * `window.__ModuleLoader__.load({ id, factory })`. This script concatenates the
 * CommonJS-style sources in `src/` (plus the two stylesheets as string modules)
 * into that form, then syntax-checks the output with `node --check`.
 *
 * Usage: node scripts/build.mjs
 */
import fs from 'node:fs';
import path from 'node:path';
import { execFileSync } from 'node:child_process';
import { fileURLToPath } from 'node:url';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const read = (relative) => fs.readFileSync(path.join(root, relative), 'utf8');

const pkg = JSON.parse(read('package.json'));
const bundleId = pkg.name;

const jsModules = ['engine', 'media', 'core', 'timeline', 'panels', 'workbench', 'ui', 'entry'];
const cssModules = ['styles.css', 'timeline.css'];

for (const id of jsModules) {
  if (!fs.existsSync(path.join(root, `src/${id}.js`))) {
    throw new Error(`missing source: src/${id}.js`);
  }
}
for (const id of cssModules) {
  if (!fs.existsSync(path.join(root, `src/${id}`))) {
    throw new Error(`missing stylesheet: src/${id}`);
  }
}

/** Reject ESM syntax — the bundled sources must stay plain CommonJS. */
function checkCommonJs(source, filename) {
  if (/^\s*import\s/m.test(source) || /^\s*export\s/m.test(source)) {
    throw new Error(`${filename}: use CommonJS (module.exports / require), not ESM import/export`);
  }
  if (source.includes('__ModuleLoader__')) {
    throw new Error(`${filename}: only entry.js may know about __ModuleLoader__`);
  }
  return source;
}

/** Wrap one source file as a registered module in the factory-local loader. */
function wrapJs(id, source) {
  const body = checkCommonJs(source, `src/${id}.js`).trimEnd();
  return [
    `    __modules[${JSON.stringify(id)}] = function (module, exports, require) {`,
    '      "use strict";',
    body,
    '    };',
    '',
  ].join('\n');
}

/** Wrap a stylesheet as a string module. */
function wrapCss(id, source) {
  return [
    `    __modules[${JSON.stringify(id)}] = function (module) {`,
    `      module.exports = ${JSON.stringify(source)};`,
    '    };',
    '',
  ].join('\n');
}

const parts = [
  `/* ${pkg.name} v${pkg.version} — generated by scripts/build.mjs. Do not edit by hand. */`,
  'window.__ModuleLoader__.load({',
  `  id: ${JSON.stringify(bundleId)},`,
  '  factory(require) {',
  '    "use strict";',
  '    const React = require("react");',
  '    const h = React.createElement;',
  '    const __modules = Object.create(null);',
  '    const __cache = Object.create(null);',
  '    function __load(id) {',
  '      if (id === "react") return React;',
  '      const key = id.startsWith("./") ? id.slice(2) : id;',
  '      if (__cache[key] !== undefined) return __cache[key].exports;',
  '      const mod = { exports: {} };',
  '      __cache[key] = mod;',
  '      const factory = __modules[key];',
  '      if (typeof factory !== "function") throw new Error("zhizhen-cut: unknown module " + id);',
  '      factory(mod, mod.exports, __load);',
  '      return mod.exports;',
  '    }',
  '',
  ...cssModules.map((id) => wrapCss(id, read(`src/${id}`))),
  ...jsModules.map((id) => wrapJs(id, read(`src/${id}.js`))),
  '    return __load("./entry");',
  '  },',
  '});',
  '',
];

const output = parts.join('\n');
const target = path.join(root, 'client.js');
fs.writeFileSync(target, output);

try {
  execFileSync(process.execPath, ['--check', target], { stdio: 'pipe' });
} catch (error) {
  throw new Error(`client.js failed node --check:\n${error.stderr?.toString() ?? error.message}`);
}

const size = (fs.statSync(target).size / 1024).toFixed(1);
const modules = [...jsModules, ...cssModules].join(', ');
console.log(`client.js written (${size} KiB, id ${bundleId})`);
console.log(`modules: ${modules}`);
