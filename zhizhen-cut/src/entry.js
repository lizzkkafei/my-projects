/** Inject the bundle stylesheet once and keep it owned by the plugin. */
function installStyles() {
  const tagId = `${PACKAGE_ID}/cutline.css`;
  const existing = document.querySelector(`style[data-cutline-css="${tagId}"]`);
  if (existing) return () => {};
  const tag = document.createElement('style');
  tag.dataset.cutline = PACKAGE_ID;
  tag.dataset.cutlineCss = tagId;
  tag.textContent = `${MAIN_CSS}\n${TIMELINE_CSS}`;
  document.head.append(tag);
  return () => {
    tag.remove();
  };
}

const inject = ['slots', 'locale'];

/**
 * Wire the bundle into the Client: dictionary, stylesheet, composer entry,
 * full-frame overlay, and the global ⌥C shortcut.
 * @param ctx Client root context.
 */
function apply(ctx) {
  ctx.effect(() => ctx.locale.register(LOCALE_NS, { zh, en }), 'cutline: dictionaries');
  const translate = ctx.locale.bind(LOCALE_NS);
  core.setTranslator(translate);

  ctx.effect(installStyles, 'cutline: styles');

  ctx.slots.inject('conversation.input.left', () =>
    ctx.slots.register(
      {
        name: 'conversation.input.left',
        id: 'zhizhen-cut',
        order: 20,
        locale: LOCALE_NS,
      },
      ui.EntryButton,
    ),
  );

  ctx.slots.inject('shell.overlay', () =>
    ctx.slots.register(
      {
        name: 'shell.overlay',
        id: 'zhizhen-cut',
        order: 80,
        locale: LOCALE_NS,
      },
      ui.WorkbenchOverlay,
    ),
  );

  ctx.effect(() => {
    const onKeyDown = (event) => {
      if (!event.altKey || event.metaKey || event.ctrlKey) return;
      if (String(event.key).toLowerCase() !== 'c' && event.code !== 'KeyC') return;
      const target = event.target;
      const tag = target && target.tagName;
      if (tag === 'INPUT' || tag === 'TEXTAREA' || tag === 'SELECT' || (target && target.isContentEditable)) {
        return;
      }
      event.preventDefault();
      event.stopPropagation();
      core.store.openWorkbench();
    };
    window.addEventListener('keydown', onKeyDown, true);
    return () => window.removeEventListener('keydown', onKeyDown, true);
  }, 'cutline: open shortcut');
}

module.exports = { inject, apply };
